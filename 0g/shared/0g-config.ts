// ─── Unit Conversion ────────────────────────────────────────────────────────
//
// Game uses "cents" internally (100 cents = 1 game dollar).
// 0G uses 18-decimal A0GI (wei).
// Mapping: 1 cent = 1e14 wei  =>  100 cents (1 game dollar) = 0.01 A0GI
//          10000 cents ($100 game) = 1.0 A0GI
//
// This keeps game economics similar to the Initia CHIP mapping while using
// 0G's native token for on-chain settlements.

const WEI_PER_CENT = BigInt("100000000000000") // 1e14

/**
 * Convert game cents to 0G wei (bigint).
 * Example: centsToWei(20) => 2000000000000000n (0.002 A0GI for a $0.20 bet)
 */
export function centsToWei(cents: number): bigint {
  return BigInt(Math.round(cents)) * WEI_PER_CENT
}

/**
 * Convert 0G wei to game cents (number).
 * Example: weiToCents(2000000000000000n) => 20
 */
export function weiToCents(wei: bigint | string): number {
  return Number(BigInt(wei) / WEI_PER_CENT)
}

/**
 * Format a wei amount as a human-readable 0G string.
 * Example: formatZg(2000000000000000n) => "0.002 0G"
 *          formatZg(1000000000000000000n) => "1.0 0G"
 */
export function formatZg(wei: bigint | string | number): string {
  const w = BigInt(wei)
  const whole = w / BigInt("1000000000000000000")
  const frac = w % BigInt("1000000000000000000")

  // Convert fraction to a decimal string with up to 6 significant digits
  if (frac === 0n) {
    return `${whole}.0 0G`
  }

  // Pad fraction to 18 digits, then trim trailing zeros but keep at least 1
  const fracStr = frac.toString().padStart(18, "0")
  const trimmed = fracStr.replace(/0+$/, "") || "0"
  // Cap at 6 decimal digits for readability
  const display = trimmed.length > 6 ? trimmed.slice(0, 6) : trimmed

  return `${whole}.${display} 0G`
}

