// ─── Wallet Addresses ───────────────────────────────────────────────────────
//
// Agent wallets are loaded from 0g/data/wallets.json if it exists.
// The file is generated by 0g/scripts/fund-agents.ts after wallet creation.
// Format: { "Llama": { "address": "0x...", "keyFile": "llama.json" }, ... }

interface WalletEntry {
  address: string
  keyFile?: string
}

function loadWallets(): Record<string, WalletEntry> {
  const walletsPath = join(__dirname, "..", "data", "wallets.json")
  try {
    if (existsSync(walletsPath)) {
      const raw = readFileSync(walletsPath, "utf-8")
      return JSON.parse(raw) as Record<string, WalletEntry>
    }
  } catch (err) {
    console.warn(`[0G-CONFIG] Failed to load wallets from ${walletsPath}: ${(err as Error).message?.slice(0, 80)}`)
  }
  return {}
}

export const ZG_WALLETS: Record<string, WalletEntry> = loadWallets()

/**
 * Get wallet address for an agent name. Returns empty string if not found.
 */
export function getWalletAddress(agentName: string): string {
  return ZG_WALLETS[agentName]?.address ?? ""
}

